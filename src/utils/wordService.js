// 🔹 Evaluate each letter of the guess against the target
export function evaluateGuess(guess, target) {
  const guessLetters = guess.toLowerCase().split("");
  const targetLetters = target.title.toLowerCase().split("");
  const result = Array(guessLetters.length).fill("absent");

  // Mark correct letters first
  for (let i = 0; i < guessLetters.length; i++) {
    if (guessLetters[i] === targetLetters[i]) {
      result[i] = "correct";
      targetLetters[i] = null;
    }
  }

  // Mark present letters next
  for (let i = 0; i < guessLetters.length; i++) {
    if (result[i] === "correct") continue;
    const idx = targetLetters.indexOf(guessLetters[i]);
    if (idx !== -1) {
      result[i] = "present";
      targetLetters[idx] = null;
    }
  }

  return result;
}